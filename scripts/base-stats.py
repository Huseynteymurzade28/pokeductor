#!/usr/bin/env python3
"""Regenerates src/base_stats.tsv, the built-in base stat and type table.

Stat terms in the search box (`spe>=110`, `bst>600`), the stat sort orders and
the party card's suggestions need every entry's base stats and types, which
PokeAPI only serves one `/pokemon/{name}` request at a time. Rather than fetch
thirteen hundred records for a keypress, the binary carries a table, generated
here from the CSV files PokeAPI itself is built from. Names are PokeAPI's
identifiers, the same ones the master list uses, alternate forms included.

Run it after a new generation lands in PokeAPI:

    python3 scripts/base-stats.py > src/base_stats.tsv

Standard library only.
"""

import csv
import io
import sys
import urllib.request

SOURCE = "https://raw.githubusercontent.com/PokeAPI/pokeapi/master/data/v2/csv"

# PokeAPI's stat ids, in the order the table's columns use. 7 and 8 are the
# battle-only accuracy and evasion stages, which no species has a base for.
STAT_IDS = [1, 2, 3, 4, 5, 6]


def fetch(name):
    with urllib.request.urlopen(f"{SOURCE}/{name}") as response:
        return list(csv.DictReader(io.TextIOWrapper(response, encoding="utf-8")))


def main():
    names = {int(row["id"]): row["identifier"] for row in fetch("pokemon.csv")}
    stats = {}
    for row in fetch("pokemon_stats.csv"):
        stats.setdefault(int(row["pokemon_id"]), {})[int(row["stat_id"])] = int(
            row["base_stat"]
        )

    type_names = {int(row["id"]): row["identifier"] for row in fetch("types.csv")}
    types = {}
    for row in fetch("pokemon_types.csv"):
        types.setdefault(int(row["pokemon_id"]), {})[int(row["slot"])] = type_names[
            int(row["type_id"])
        ]

    out = sys.stdout
    out.write("# Generated by scripts/base-stats.py from PokeAPI's CSV data.\n")
    out.write("# name\thp\tatk\tdef\tspa\tspd\tspe\ttype1\ttype2\n")
    for pokemon_id in sorted(names):
        row = stats.get(pokemon_id, {})
        if any(stat not in row for stat in STAT_IDS):
            sys.exit(f"{names[pokemon_id]} is missing a base stat")
        slots = types.get(pokemon_id, {})
        if 1 not in slots:
            sys.exit(f"{names[pokemon_id]} has no type")
        values = "\t".join(str(row[stat]) for stat in STAT_IDS)
        # A single type leaves the second column as `-` rather than empty, so
        # every row has the same number of fields.
        out.write(f"{names[pokemon_id]}\t{values}\t{slots[1]}\t{slots.get(2, '-')}\n")


if __name__ == "__main__":
    main()
